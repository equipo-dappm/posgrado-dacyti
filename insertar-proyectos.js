// --- Consulta de inserción -------------------------------------------------
// Inserta el anteproyecto solo si el alumno existe y aún no tiene uno
// del mismo tipo (evita duplicados).
const insert = db.prepare(`
  INSERT INTO proyectos (alumno_id, nombre, tipo_id)
  SELECT a.id, ?, tp.id
  FROM alumnos a
  JOIN tipos_proyecto tp ON tp.nombre = 'Anteproyecto'
  WHERE a.matricula = ?
    AND NOT EXISTS (
      SELECT 1
      FROM proyectos p
      WHERE p.alumno_id = a.id
        AND p.tipo_id = tp.id
    )
`);

// Ejecuta todas las inserciones dentro de una transacción única.
const tx = db.transaction(() => {
  for (const [matricula, nombre] of datos) {
    insert.run(nombre, matricula);
  }
});

tx();

// --- Reporte final ---------------------------------------------------------
const total = db.prepare(`
  SELECT COUNT(*) AS total
  FROM proyectos
`).get();

console.log("Registros procesados:", datos.length);
console.log("Anteproyectos en la BD:", total.total);

db.close();
