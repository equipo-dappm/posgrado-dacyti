-- En conflicto (alumno+documento ya existe) actualiza el estado.
INSERT INTO alumno_documento
    (alumno_id, tipo_documento_id, estado_id)
SELECT
    a.id,
    td.id,
    CASE d.clave
        WHEN 'F1' THEN datos.f1
        WHEN 'F2' THEN datos.f2
        WHEN 'F3' THEN datos.f3
        WHEN 'F4' THEN datos.f4
        WHEN 'F5' THEN datos.f5
        WHEN 'EV1' THEN datos.ev1
        WHEN 'EV2' THEN datos.ev2
        WHEN 'EV7' THEN datos.ev7
    END
FROM datos
JOIN alumnos a ON a.matricula = datos.matricula
CROSS JOIN documentos d
JOIN tipos_documento td ON td.clave = d.clave
ON CONFLICT(alumno_id, tipo_documento_id)
DO UPDATE SET estado_id = excluded.estado_id;

